package com.freease.music

import com.freease.music.data.model.Song
import com.freease.music.data.youtube.YouTubeRepository
import com.freease.music.playback.CanvasResolver
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class CanvasTest {
    private val song = Song("atv1", "Ditto", "NewJeans", durationSec = 186)

    @Test
    fun skipsAlteredVersions() {
        val cands = listOf(
            Song("a", "Ditto (250 remix) (instrumental)", "NewJeans", durationSec = 214),
            Song("b", "Ditto Lyrics", "NewJeans", durationSec = 190),
            Song("c", "Ditto", "NewJeans", durationSec = 279),
            Song("d", "OMG", "NewJeans", durationSec = 213),
        )
        assertEquals("c", CanvasResolver.pickVideo(song, cands)?.id)
        assertNull(CanvasResolver.pickVideo(song, cands.take(2)))
    }

    @Test
    fun officialChannelOnly() {
        assertTrue(CanvasResolver.officialChannel("NewJeans", "NewJeans"))
        assertTrue(CanvasResolver.officialChannel("TulusVEVO", "Tulus"))
        assertTrue(CanvasResolver.officialChannel("HYBE LABELS", "NewJeans").not())
        assertTrue(CanvasResolver.officialChannel("Lady Gaga", "Lady Gaga, Bruno Mars"))
        assertFalse(CanvasResolver.officialChannel("Dan Music", "Coldplay"))
        assertFalse(CanvasResolver.officialChannel("7clouds", "Lady Gaga"))
    }

    @Test
    fun autoGeneratedDetection() {
        assertTrue(YouTubeRepository.isAutoGenerated("Provided to YouTube by Universal\n\nDitto · NewJeans\n\nAuto-generated by YouTube.", "NewJeans"))
        assertTrue(YouTubeRepository.isAutoGenerated(null, "Tulus - Topic"))
        assertFalse(YouTubeRepository.isAutoGenerated("Official music video", "Tulus"))
    }

    @Test
    fun startPoint() {
        assertEquals(60_000, CanvasResolver.startFor(180))
        assertEquals(30_000, CanvasResolver.startFor(0))
    }
}
