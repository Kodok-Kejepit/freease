package com.freease.music

import com.freease.music.data.youtube.NewPipeHttp
import com.freease.music.data.youtube.YouTubeRepository
import okhttp3.OkHttpClient
import okhttp3.Request
import org.junit.Assume
import org.junit.Test
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.StreamInfo
import java.io.File

class CaptionProbe {
    @Test
    fun probe() {
        val f = File("caption.on")
        Assume.assumeTrue(f.exists())
        val client = OkHttpClient()
        YouTubeRepository.initNewPipe(NewPipeHttp(client), "ID")
        val out = StringBuilder()
        for (id in f.readLines().map { it.trim() }.filter { it.isNotEmpty() }) {
            val info = StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$id")
            out.appendLine("##### $id ${info.name} dur=${info.duration}")
            for (s in info.subtitles) {
                out.appendLine("sub ${s.languageTag} auto=${s.isAutoGenerated} ${s.format}")
                val body = client.newCall(Request.Builder().url(s.content).build()).execute().use { it.body?.string() ?: "" }
                out.appendLine(body.take(2500))
            }
        }
        File("build/caption.txt").writeText(out.toString())
    }
}
